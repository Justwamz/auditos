import pg from 'pg';
process.loadEnvFile(new URL('../../.env.local', import.meta.url));
const u = new URL(process.env.PG_SUPERUSER_URL);
const c = new pg.Client({ host: u.hostname, port: Number(u.port), user: u.username, password: decodeURIComponent(u.password), database: 'postgres' });
await c.connect();
const dbName = process.argv[2] ?? 'auditos_test';
if (!/^auditos_(test|e2e)$/.test(dbName)) throw new Error('refusing to drop ' + dbName);
await c.query(`drop database if exists ${dbName} with (force)`);
await c.end();
console.log(dbName + ' dropped');
